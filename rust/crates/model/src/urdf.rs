//! URDF generation (port of cmodel_parser.generate_urdf)
use crate::{fnum, pstr};
use serde_json::Value;
use std::f64::consts::PI;

const SMALL: &str = "<inertial><origin xyz=\"0 0 0\" rpy=\"0 0 0\"/><mass value=\"0.05\"/><inertia ixx=\"1e-4\" ixy=\"0\" ixz=\"0\" iyy=\"1e-4\" iyz=\"0\" izz=\"1e-4\"/></inertial>";

fn box_inertia(m: f64, x: f64, y: f64, z: f64) -> (f64, f64, f64) { (m * (y * y + z * z) / 12.0, m * (x * x + z * z) / 12.0, m * (x * x + y * y) / 12.0) }
fn cyl_inertia(m: f64, r: f64, h: f64) -> (f64, f64, f64) { let ixx = m * (3.0 * r * r + h * h) / 12.0; (ixx, m * r * r / 2.0, ixx) }
fn inertial(x: &mut Vec<String>, m: f64, ixx: f64, iyy: f64, izz: f64, origin: &str) {
    x.push(format!("    <inertial><origin xyz=\"{origin}\" rpy=\"0 0 0\"/><mass value=\"{m:.4}\"/><inertia ixx=\"{ixx:.5}\" ixy=\"0\" ixz=\"0\" iyy=\"{iyy:.5}\" iyz=\"0\" izz=\"{izz:.5}\"/></inertial>"));
}
fn n(v: &Value, k: &str, d: f64) -> f64 { fnum(v.get(k), d) }
fn s<'a>(v: &'a Value, k: &str) -> &'a str { v.get(k).and_then(|x| x.as_str()).unwrap_or("") }

pub fn generate_urdf(spec: &Value) -> String {
    let ch = &spec["chassis"];
    let (head, tail, left, right) = (n(ch, "head_offset_m", 0.0), n(ch, "tail_offset_m", 0.0), n(ch, "left_offset_m", 0.0), n(ch, "right_offset_m", 0.0));
    let (l_, w_, h_) = (head + tail, left + right, n(ch, "height_m", 0.0));
    let (x_c, y_c) = ((head - tail) / 2.0, (left - right) / 2.0);
    let wheels: Vec<Value> = spec.get("wheels").and_then(|w| w.as_array()).cloned().unwrap_or_default();
    let r_min = wheels.iter().map(|w| n(w, "radius_m", 0.0)).fold(f64::INFINITY, f64::min);
    let r_min = if wheels.is_empty() { 0.1 } else { r_min };
    let clearance = crate::rnd((0.02f64).max(r_min * 0.5), 4);
    let base_h = if h_ > 0.6 { h_.min(0.35) } else { h_ };
    let upper_h = if h_ > 0.6 { h_ - base_h - clearance } else { 0.0 };
    let mass = { let m = n(ch, "mass_kg", 0.0); if m == 0.0 { 150.0 } else { m } };
    let wheel_mass = 5.0;
    let body_mass = (10.0f64).max(mass - wheels.iter().map(|w| n(w, "mass_kg", wheel_mass)).sum::<f64>());
    let mut x: Vec<String> = vec![
        "<?xml version=\"1.0\"?>".into(),
        format!("<!-- Auto-generated by cmodel_parser.py from {} (schema v{}) -->", spec.get("model_file").map(pstr).unwrap_or_default(), spec.get("schema_version").map(pstr).unwrap_or("None".into())),
        format!("<!-- chassis={} ({}), base_link = 运动中心(motion center), 地面高度 -->", pstr(&ch["type"]), ch.get("cmodel_type").map(pstr).unwrap_or_default()),
        format!("<robot name=\"{}\">", spec.get("robot_name").map(pstr).unwrap_or("cmodel_agv".into())),
        "  <material name=\"body\"><color rgba=\"0.95 0.55 0.1 1\"/></material>".into(),
        "  <material name=\"upper\"><color rgba=\"0.85 0.85 0.88 0.6\"/></material>".into(),
        "  <material name=\"rubber\"><color rgba=\"0.15 0.15 0.15 1\"/></material>".into(),
        "  <material name=\"steel\"><color rgba=\"0.55 0.58 0.62 1\"/></material>".into(),
        "  <material name=\"sensor\"><color rgba=\"0.0 0.8 0.95 1\"/></material>".into(),
        "  <material name=\"camera\"><color rgba=\"0.6 0.2 0.9 1\"/></material>".into(),
        "  <link name=\"base_footprint\"/>".into(),
        "  <joint name=\"base_footprint_joint\" type=\"fixed\"><parent link=\"base_footprint\"/><child link=\"base_link\"/><origin xyz=\"0 0 0\" rpy=\"0 0 0\"/></joint>".into(),
        "  <link name=\"base_link\">".into()];
    let zc = clearance + base_h / 2.0;
    x.push(format!("    <visual><origin xyz=\"{x_c:.4} {y_c:.4} {zc:.4}\"/><geometry><box size=\"{l_:.4} {w_:.4} {base_h:.4}\"/></geometry><material name=\"body\"/></visual>"));
    x.push(format!("    <collision><origin xyz=\"{x_c:.4} {y_c:.4} {zc:.4}\"/><geometry><box size=\"{l_:.4} {w_:.4} {base_h:.4}\"/></geometry></collision>"));
    let (ixx, iyy, izz) = box_inertia(body_mass, l_, w_, base_h);
    let com_s = match ch.get("com").and_then(|c| c.as_array()) { Some(c) if c.len() == 3 => format!("{:.4} {:.4} {:.4}", fnum(c.get(0), 0.0), fnum(c.get(1), 0.0), fnum(c.get(2), 0.0)), _ => format!("{x_c:.4} {y_c:.4} {zc:.4}") };
    inertial(&mut x, body_mass, ixx, iyy, izz, &com_s);
    x.push("  </link>".into());
    if upper_h > 0.05 {
        let zu = clearance + base_h + upper_h / 2.0;
        x.push("  <link name=\"upper_body_link\">".into());
        x.push(format!("    <visual><origin xyz=\"0 0 0\"/><geometry><box size=\"{l_:.4} {w_:.4} {upper_h:.4}\"/></geometry><material name=\"upper\"/></visual>"));
        x.push(format!("    {SMALL}"));
        x.push("  </link>".into());
        x.push(format!("  <joint name=\"upper_body_joint\" type=\"fixed\"><parent link=\"base_link\"/><child link=\"upper_body_link\"/><origin xyz=\"{x_c:.4} {y_c:.4} {zu:.4}\" rpy=\"0 0 0\"/></joint>"));
    }
    for w in &wheels {
        let (nm, r) = (s(w, "name"), n(w, "radius_m", 0.0));
        let wid = n(w, "width_m", 0.05);
        let kind = s(w, "kind");
        let (wx, wy) = (n(w, "x", 0.0), n(w, "y", 0.0));
        if kind == "caster" {
            x.push(format!("  <link name=\"{nm}_link\">"));
            x.push(format!("    <visual><geometry><sphere radius=\"{r:.4}\"/></geometry><material name=\"steel\"/></visual>"));
            x.push(format!("    <collision><geometry><sphere radius=\"{r:.4}\"/></geometry></collision>"));
            let i = 0.4 * 1.0 * r * r;
            inertial(&mut x, 1.0, i, i, i, "0 0 0");
            x.push("  </link>".into());
            x.push(format!("  <joint name=\"{nm}_joint\" type=\"fixed\"><parent link=\"base_link\"/><child link=\"{nm}_link\"/><origin xyz=\"{wx:.4} {wy:.4} {r:.4}\" rpy=\"0 0 0\"/></joint>"));
            continue;
        }
        let mut parent = "base_link".to_string();
        let mut origin = format!("{wx:.4} {wy:.4} {r:.4}");
        if kind == "steer" {
            x.push(format!("  <link name=\"{nm}_steer_link\">"));
            x.push(format!("    <visual><origin xyz=\"0 0 {:.4}\"/><geometry><cylinder radius=\"{:.4}\" length=\"{:.4}\"/></geometry><material name=\"steel\"/></visual>", r * 0.9, r * 0.8, r * 0.4));
            inertial(&mut x, 2.0, 0.01, 0.01, 0.01, "0 0 0");
            x.push("  </link>".into());
            let vel = n(w, "steer_rate_radps", 1.5);
            x.push(format!("  <joint name=\"{nm}_steer_joint\" type=\"revolute\"><parent link=\"base_link\"/><child link=\"{nm}_steer_link\"/><origin xyz=\"{origin}\" rpy=\"0 0 0\"/><axis xyz=\"0 0 1\"/><limit lower=\"{:.5}\" upper=\"{:.5}\" effort=\"500.0\" velocity=\"{vel:.4}\"/></joint>", n(w, "steer_min_rad", 0.0), n(w, "steer_max_rad", 0.0)));
            parent = format!("{nm}_steer_link");
            origin = "0 0 0".into();
        }
        x.push(format!("  <link name=\"{nm}_link\">"));
        x.push(format!("    <visual><origin xyz=\"0 0 0\" rpy=\"1.5708 0 0\"/><geometry><cylinder radius=\"{r:.4}\" length=\"{wid:.4}\"/></geometry><material name=\"rubber\"/></visual>"));
        x.push(format!("    <collision><origin xyz=\"0 0 0\" rpy=\"1.5708 0 0\"/><geometry><cylinder radius=\"{r:.4}\" length=\"{wid:.4}\"/></geometry></collision>"));
        let wm = n(w, "mass_kg", wheel_mass);
        let (ixx, iyy, izz) = cyl_inertia(wm, r, wid);
        inertial(&mut x, wm, ixx, iyy, izz, "0 0 0");
        x.push("  </link>".into());
        let jn = if kind == "steer" { format!("{nm}_drive_joint") } else { format!("{nm}_joint") };
        let max_v = n(w, "max_speed_mps", 2.0) / r.max(1e-3);
        x.push(format!("  <joint name=\"{jn}\" type=\"continuous\"><parent link=\"{parent}\"/><child link=\"{nm}_link\"/><origin xyz=\"{origin}\" rpy=\"0 0 0\"/><axis xyz=\"0 1 0\"/><limit effort=\"200\" velocity=\"{max_v:.3}\"/></joint>"));
    }
    let imu = spec.get("imu").cloned().unwrap_or(Value::Null);
    x.push(format!("  <link name=\"imu_link\">{SMALL}</link>"));
    x.push(format!("  <joint name=\"imu_joint\" type=\"fixed\"><parent link=\"base_link\"/><child link=\"imu_link\"/><origin xyz=\"{:.4} {:.4} {:.4}\" rpy=\"0 0 0\"/></joint>", n(&imu, "x", 0.0), n(&imu, "y", 0.0), n(&imu, "z", 0.1)));
    for li in spec.get("lidars").and_then(|l| l.as_array()).cloned().unwrap_or_default() {
        let nm = s(&li, "name");
        let hs = li.get("housing").cloned().unwrap_or(Value::Null);
        let geo = if let Some(c) = hs.get("cylinder_d_h").filter(|c| crate::overrides::truthy(c)) {
            format!("<cylinder radius=\"{:.4}\" length=\"{:.4}\"/>", fnum(c.get(0), 0.0) / 2.0, fnum(c.get(1), 0.0))
        } else if let Some(b) = hs.get("box").filter(|b| crate::overrides::truthy(b)) {
            format!("<box size=\"{:.4} {:.4} {:.4}\"/>", fnum(b.get(0), 0.0), fnum(b.get(1), 0.0), fnum(b.get(2), 0.0))
        } else { "<cylinder radius=\"0.04\" length=\"0.06\"/>".into() };
        x.push(format!("  <link name=\"{nm}_link\"><visual><geometry>{geo}</geometry><material name=\"sensor\"/></visual>{SMALL}</link>"));
        x.push(format!("  <joint name=\"{nm}_joint\" type=\"fixed\"><parent link=\"base_link\"/><child link=\"{nm}_link\"/><origin xyz=\"{:.4} {:.4} {:.4}\" rpy=\"{:.5} {:.5} {:.5}\"/></joint>",
            n(&li, "x", 0.0), n(&li, "y", 0.0), n(&li, "z", 0.0), n(&li, "roll", 0.0), n(&li, "pitch", 0.0), n(&li, "yaw", 0.0)));
    }
    let opt = format!("{:.5} 0 {:.5}", -PI / 2.0, -PI / 2.0);
    for cam in spec.get("cameras").and_then(|c| c.as_array()).cloned().unwrap_or_default() {
        let nm = s(&cam, "name");
        let t = cam.get("type").and_then(|t| t.as_str());
        let ctype = if t == Some("depthCamera") { Some("tof") } else { t };
        let mut pitch = n(&cam, "pitch", 0.0);
        if matches!(ctype, Some("codeReader") | None) {
            let o = s(&cam, "orientation");
            pitch += if o.ends_with("DOWN") { PI / 2.0 } else if o.ends_with("UP") { -PI / 2.0 } else { 0.0 };
        }
        let size = match ctype { Some("stereo") => format!("0.03 {:.3} 0.03", n(&cam, "baseline_m", 0.05) + 0.04), Some("tof") => "0.03 0.06 0.03".into(), _ => "0.03 0.05 0.03".into() };
        x.push(format!("  <link name=\"{nm}_link\"><visual><geometry><box size=\"{size}\"/></geometry><material name=\"camera\"/></visual>{SMALL}</link>"));
        x.push(format!("  <joint name=\"{nm}_joint\" type=\"fixed\"><parent link=\"base_link\"/><child link=\"{nm}_link\"/><origin xyz=\"{:.4} {:.4} {:.4}\" rpy=\"{:.5} {:.5} {:.5}\"/></joint>",
            n(&cam, "x", 0.0), n(&cam, "y", 0.0), n(&cam, "z", 0.0), n(&cam, "roll", 0.0), pitch, n(&cam, "yaw", 0.0)));
        x.push(format!("  <link name=\"{nm}_optical_frame\"/>"));
        x.push(format!("  <joint name=\"{nm}_optical_joint\" type=\"fixed\"><parent link=\"{nm}_link\"/><child link=\"{nm}_optical_frame\"/><origin xyz=\"0 0 0\" rpy=\"{opt}\"/></joint>"));
        if ctype == Some("stereo") {
            let b = n(&cam, "baseline_m", 0.05);
            x.push(format!("  <link name=\"{nm}_right_optical_frame\"/>"));
            x.push(format!("  <joint name=\"{nm}_right_optical_joint\" type=\"fixed\"><parent link=\"{nm}_link\"/><child link=\"{nm}_right_optical_frame\"/><origin xyz=\"0 {:.4} 0\" rpy=\"{opt}\"/></joint>", -b));
        }
    }
    for pe in spec.get("photoelectric").and_then(|p| p.as_array()).cloned().unwrap_or_default() {
        let nm = s(&pe, "name");
        x.push(format!("  <link name=\"{nm}_pe_link\"><visual><geometry><box size=\"0.02 0.02 0.02\"/></geometry><material name=\"sensor\"/></visual>{SMALL}</link>"));
        x.push(format!("  <joint name=\"{nm}_pe_joint\" type=\"fixed\"><parent link=\"base_link\"/><child link=\"{nm}_pe_link\"/><origin xyz=\"{:.4} {:.4} {:.4}\" rpy=\"0 0 {:.5}\"/></joint>", n(&pe, "x", 0.0), n(&pe, "y", 0.0), n(&pe, "z", 0.12), n(&pe, "yaw", 0.0)));
    }
    let lift = spec.get("lift").cloned().unwrap_or(Value::Null);
    if lift.get("enabled").map(crate::overrides::truthy).unwrap_or(false) {
        let sz: Vec<f64> = match lift.get("size").and_then(|z| z.as_array()).filter(|z| !z.is_empty()) { Some(z) => z.iter().map(|v| fnum(Some(v), 0.0)).collect(), None => vec![1.0, 0.7, 0.04] };
        let stroke = n(&lift, "stroke_m", 0.08);
        x.push(format!("  <link name=\"lift_link\"><visual><geometry><box size=\"{:.3} {:.3} {:.3}\"/></geometry><material name=\"steel\"/></visual><collision><geometry><box size=\"{:.3} {:.3} {:.3}\"/></geometry></collision>", sz[0], sz[1], sz[2], sz[0], sz[1], sz[2]));
        let lm = n(&lift, "mass_kg", 20.0);
        let (a, b, c) = box_inertia(lm, sz[0], sz[1], sz[2]);
        inertial(&mut x, lm, a, b, c, "0 0 0");
        x.push("  </link>".into());
        x.push(format!("  <joint name=\"lift_joint\" type=\"prismatic\"><parent link=\"base_link\"/><child link=\"lift_link\"/><origin xyz=\"{:.4} {:.4} {:.4}\" rpy=\"0 0 0\"/><axis xyz=\"0 0 1\"/><limit lower=\"0\" upper=\"{stroke:.4}\" effort=\"5000\" velocity=\"{:.4}\"/></joint>",
            n(&lift, "x", 0.0), n(&lift, "y", 0.0), n(&lift, "z", 0.3), n(&lift, "speed_mps", 0.02)));
    }
    x.push("</robot>".into());
    x.join("\n") + "\n"
}
